#!/usr/bin/env python3
"""Write the shareable Doom patch into nek100-mod's target, for its CLI and web patcher (Extra > DOOM).

Only Freedoom with our own map (wad.shareable()): the patch carries their textures, sprites and music.
Effects on the GM drums (--sfx drums), so the patch works next to an instrument added in soundbank slot 500.
Then regenerate the web patcher there: python3 -m nuxdsp web NEK100_DSP_V1.0.7.bin

usage: .venv/bin/python tools/exportpatch.py [--music E4M8] [--out PATH]
"""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "tools"), str(ROOT / "firmware"), str(ROOT / "cc")]
import wad

OUT = ROOT.parent / "nek100-mod" / "targets" / "nek100-dsp-1.0.7" / "patches" / "doom_demo.patch"
TITLE = "DOOM in Extra: the Hangar map with Freedoom's textures, sprites and music (unofficial port, doom-piano)"
NOTICE = """; Generated by doom-piano/tools/exportpatch.py, do not edit by hand.
; Engine: doom-piano. Map: Hangar (doom-piano's own, maps/hangar.wad). Level song: {song}, title: {intro}.
; Textures, sprites, music: Freedoom Phase 1 (https://freedoom.github.io), Copyright (c) 2001-2024 Contributors to
; the Freedoom project, BSD 3-clause license. Title: the DOOM logo (Wikimedia Commons, public domain as a text
; logo). DOOM is a trademark of id Software; this port is not affiliated with or endorsed by id.
; Freedoom's license (art/FREEDOOM-COPYING.txt):
"""


def text(music=None):
    import doom
    wad.use(music=music)
    if not wad.shareable():
        raise SystemExit("only Freedoom with our own map is exported (wad.shareable())")
    doom.SFX_DRUMS = True
    t = doom.patch()
    lines = t.split("\n")
    assert lines[0] == ".patch doom_demo" and lines[1].startswith(".title ")
    lines[1] = '.title "%s"' % TITLE
    notice = NOTICE.format(song=wad.SONG, intro=wad.INTRO) + "".join(
        (";   " + l).rstrip() + "\n" for l in (ROOT / "art" / "FREEDOOM-COPYING.txt").read_text().splitlines())
    lines[3] = notice.rstrip("\n") + "\n" + lines[3].replace(
        "Local generated output: contains WAD-derived data. ", "")
    return "\n".join(lines)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--music", help="the level's song (default: E4M8)")
    p.add_argument("--out", type=Path, default=OUT)
    a = p.parse_args()
    a.out.write_text(text(a.music))
    print("wrote", a.out, "(%d KB)" % (a.out.stat().st_size // 1024))
