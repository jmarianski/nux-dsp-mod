#!/usr/bin/env python3
"""Generate fb_splash.patch: a full-screen 128x64 test image drawn straight into the NEK-100 framebuffer.

Step 1 towards Doom on the piano's own display. The patch hooks the volume change on the main screen
(VOL+ / VOL-): instead of redrawing the VOL number, it copies a whole frame into the framebuffer and sets the
"refresh LCD" flag, so the firmware's tick sends all 8 pages to the display.

Framebuffer (from the firmware map / our analysis, not yet confirmed on the device for a full frame):
    RAM 0x662a, 1024 words, byte i = page*128 + x, bit b of it = row page*8 + b (bit 0 = top), one byte per word.
    RAM 0x6a50 bit 0 = "send the framebuffer to the LCD" (cleared by the tick after sending).
The image is stored packed, two framebuffer bytes per program word (low byte first), and unpacked by the copy loop.

The test card is chosen to make mistakes visible: a filled square marks the top-left corner (mirroring,
rotation), the border shows the edges (off-by-one, missing pages), the 1-px checkerboard shows bit order
within a page, and the stripes at the bottom show page order.

Usage: python3 firmware/splash.py [OUT.patch]   (needs ../nek100-mod next to this repo for its pixel font)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "nek100-mod"))
from nuxdsp import pixfont  # noqa: E402

W, H = 128, 64


def blit(canvas, rows, x0, y0, scale=1):
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                for dy in range(scale):
                    for dx in range(scale):
                        canvas[y0 + y * scale + dy][x0 + x * scale + dx] = 1


def centred(canvas, text, y0, font, scale):
    rows, w = pixfont.render(text, font)
    blit(canvas, rows, (W - w * scale) // 2, y0, scale)


def test_card():
    c = [[0] * W for _ in range(H)]
    for x in range(W):
        c[0][x] = c[H - 1][x] = 1
    for y in range(H):
        c[y][0] = c[y][W - 1] = 1
    for y in range(2, 8):                       # top-left marker
        for x in range(2, 8):
            c[y][x] = 1
    centred(c, "DOOM", 0, "small", 4)           # 5 px letters x4 = 20 px (rows 4..23)
    centred(c, "PIANO", 22, "small", 2)         # rows 24..33
    centred(c, "NEK-100 FRAMEBUFFER", 35, "small", 1)  # rows 36..40
    for y in range(44, 52):                     # 1-px checkerboard
        for x in range(8, 120):
            c[y][x] = (x + y) & 1
    for y in range(54, 62):                     # vertical stripes of growing width
        x, w = 4, 1
        while x + w < W - 4:
            for i in range(w):
                c[y][x + i] = 1
            x += 2 * w
            w += 1
    return c


def pack(canvas):
    fb = []
    for page in range(H // 8):
        for x in range(W):
            fb.append(sum(canvas[page * 8 + b][x] << b for b in range(8)))
    return [fb[i] | fb[i + 1] << 8 for i in range(0, len(fb), 2)]


PATCH = """\
.patch fb_splash
.title "doom-piano step 1: VOL+/VOL- on the main screen shows a full-screen 128x64 test image"
; Generated by doom-piano/firmware/splash.py, do not edit by hand. Our own code and image only.
; The volume still changes; the next full redraw of the main screen brings the normal view back.

.hook 0x03fce expect 0xd7c8 0x54a8     ; volume handler, op 0, main screen: ccall of the VOL redraw
    call  fbs_draw
.end

.code
fbs_draw:                               ; copy the packed image into the framebuffer, ask for a refresh
    li    r4, #framebuffer              ; r4 = destination (RAM), runs on through both halves
    li    r5, #fbs_img1                 ; the image is split in two blocks: bank 0 has no 512 free words in one piece
    li    r3, #fbs_end1
    call  fbs_copy
    li    r5, #fbs_img2
    li    r3, #fbs_end2
    call  fbs_copy
    ld    r7, [0x6a50]                  ; bit 0: the tick sends all 8 pages to the LCD
    mov   r6, #1                        ; (the assembler has no or-immediate)
    or    r7, r6
    st    [0x6a50], r7
    ret
fbs_copy:                               ; r5 = source (program memory) .. r3, r4 = destination
    mov   r1, r5
    ldc   r7, [r1+0]                    ; two framebuffer bytes, low first
    add   r5, #1
    mov   r1, r4
    mov   r6, r7
    and   r6, #0xff
    st    [r1+0], r6
    shr   r7, 8
    st    [r1+1], r7
    add   r4, #2
    cmp   r5, r3
    bne   fbs_copy
    ret
fbs_img1:
{words1}
fbs_end1:
.end

.code
fbs_img2:
{words2}
fbs_end2:
.end
"""


def preview(canvas):
    return "\n".join("".join("#" if v else "." for v in row) for row in canvas)


def main(out):
    card = test_card()
    words = pack(card)
    def dw(ws):
        return "\n".join("    .dw " + ", ".join("0x%04x" % w for w in ws[i:i + 8]) for i in range(0, len(ws), 8))
    open(out, "w").write(PATCH.format(words1=dw(words[:256]), words2=dw(words[256:])))
    print(preview(card))
    print("wrote %s (%d image words)" % (out, len(words)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "fb_splash.patch"))
